// Finds a YouTube video for every song the stations play, a little each day (free API quota),
// and writes yt.js. Prefers the official "Artist - Topic" audio upload (same length as the
// album version, so the live schedule stays in sync), then the official video.
// Needs the YOUTUBE_API_KEY secret (see README → "YouTube player"). Safe to run any time.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { ROOT } from './shared.mjs';

const KEY = process.env.YOUTUBE_API_KEY;
const BUDGET = Number(process.env.YT_BUDGET || 95);      // 100 units per search, 10,000 units a day free
const RETRY_DAYS = 30;
const OUT = path.join(ROOT, 'yt.js');

if (!KEY) { console.log('No YOUTUBE_API_KEY set; skipping YouTube lookups.'); process.exit(0); }

// load the app's own data and engine to get the exact songs stations play
const ctx = { console, Date, Math, JSON }; ctx.window = ctx; ctx.globalThis = ctx;
for (const f of ['data.js', 'library.js', 'auto.js', 'composite.js', 'durations.js', 'history.js', 'engine.js']) {
  const p = path.join(ROOT, f); if (fs.existsSync(p)) vm.runInNewContext(fs.readFileSync(p, 'utf8'), ctx, { filename: f });
}
const E = ctx.RadioEngine;
let prev = { ids: {}, misses: {} };
if (fs.existsSync(OUT)) { const c = { window: {} }; vm.runInNewContext(fs.readFileSync(OUT, 'utf8'), c); prev = Object.assign(prev, c.window.RADIO_YT || {}); }

// priority: songs on the air now (currents, plants), then throwbacks used by the most stations
const want = new Map();
const add = (s, w) => { if (!s?.id || !s.title) return; const cur = want.get(s.id); if (cur) cur.w += w; else want.set(s.id, { song: s, w }); };
for (const s of E.SONGS.values()) add(s, s.kind === 'gold' ? 1 : 100);
for (const st of E.STATIONS) for (const g of E.goldFor(st)) add(g, 1);
const today = new Date().toISOString().slice(0, 10);
const todo = [...want.values()]
  .filter(({ song }) => !prev.ids[song.id] && !(prev.misses[song.id] && (Date.parse(today) - Date.parse(prev.misses[song.id])) / 864e5 < RETRY_DAYS))
  .sort((a, b) => b.w - a.w);
console.log(`${want.size} songs, ${Object.keys(prev.ids).length} already matched, ${todo.length} to look up; doing up to ${BUDGET} today.`);

const ent = (s) => String(s).replace(/&amp;/g, '&').replace(/&#39;|&apos;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>');
const norm = (s) => String(s || '').toLowerCase().replace(/\s*[([].*?[)\]]/g, '').replace(/\s+-\s+.*$/, '').replace(/\b(feat|ft)\b.*$/, '').replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '');
const firstArtist = (a) => String(a || '').split(/,|&| x | feat\.?| ft\.?| with /i)[0].trim();
const BAD = /\b(live|cover|karaoke|lyrics?|sped ?up|slowed|reverb|remix|instrumental|8d|nightcore|reaction|tutorial|piano)\b/i;

function pick(song, items) {
  const t = norm(song.title), a = norm(firstArtist(song.artist));
  const scored = items.map(it => {
    const title = ent(it.snippet.title), ch = ent(it.snippet.channelTitle);
    const vt = norm(title.replace(/^.*? - /, '')) || norm(title), full = title.toLowerCase().replace(/[^a-z0-9]+/g, ''), cn = norm(ch.replace(/ - Topic$/, ''));
    const titleOk = vt === t || full.includes(t);
    const artistOk = a && (cn.includes(a) || a.includes(cn) || full.includes(a));
    let score = 0;
    if (/ - Topic$/.test(ch) && artistOk) score += 6;
    else if (/vevo$/i.test(ch) || (artistOk && cn.length > 2)) score += 4;
    if (titleOk) score += 3;
    if (/official (audio|video|music video)/i.test(title)) score += 1;
    if (BAD.test(title) && !BAD.test(song.title)) score -= 6;
    return { id: it.id.videoId, score, titleOk, artistOk };
  }).filter(x => x.titleOk && x.artistOk && x.score >= 6).sort((x, y) => y.score - x.score);
  return scored[0]?.id || null;
}

let used = 0, found = 0, quotaHit = false;
for (const { song } of todo) {
  if (used >= BUDGET) break;
  const q = new URLSearchParams({ part: 'snippet', type: 'video', maxResults: '8', videoEmbeddable: 'true', videoSyndicated: 'true', regionCode: 'US', q: `${song.title} ${firstArtist(song.artist)}`, key: KEY });
  const r = await fetch('https://www.googleapis.com/youtube/v3/search?' + q);
  used++;
  if (r.status === 403) { console.log('YouTube daily quota reached; the rest will be done tomorrow.'); quotaHit = true; break; }
  if (!r.ok) { console.log(`  ${song.title} — ${song.artist}: HTTP ${r.status}`); continue; }
  const j = await r.json();
  const vid = pick(song, j.items || []);
  if (vid) { prev.ids[song.id] = vid; delete prev.misses[song.id]; found++; }
  else prev.misses[song.id] = today;
}
const out = { updated: today, ids: prev.ids, misses: prev.misses };
fs.writeFileSync(OUT, `/* Generated by scripts/youtube-ids.mjs — Spotify track id → YouTube video id */\nwindow.RADIO_YT = ${JSON.stringify(out)};\n`);
console.log(`Searched ${used}, matched ${found}. Total matched: ${Object.keys(prev.ids).length} of ${want.size}.${quotaHit ? ' (quota)' : ''}`);
